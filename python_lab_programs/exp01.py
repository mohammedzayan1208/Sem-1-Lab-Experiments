# Experiment 1: Demonstration of data types with sum of two numbers

# Integer addition
a_int = 10
b_int = 20
sum_int = a_int + b_int
print("Integer sum:", sum_int)
print("Type:", type(sum_int))
print()

# Float addition
a_float = 10.5
b_float = 4.3
sum_float = a_float + b_float
print("Float sum:", sum_float)
print("Type:", type(sum_float))
print()

# Complex number addition
a_complex = 2 + 3j
b_complex = 4 + 5j
sum_complex = a_complex + b_complex
print("Complex sum:", sum_complex)
print("Type:", type(sum_complex))
print()

# Boolean addition
a_bool = True
b_bool = False
sum_bool = a_bool + b_bool
print("Boolean sum:", sum_bool)
print("Type:", type(sum_bool))
print()

# Boolean logical operations
result_and = a_bool and b_bool
print("Boolean AND:", result_and)
print("Type:", type(result_and))
print()

result_or = a_bool or b_bool
print("Boolean OR:", result_or)
print("Type:", type(result_or))
print()

result_not = not a_bool
print("Boolean NOT:", result_not)
print("Type:", type(result_not))
print()

# String concatenation
a_str = "Hello "
b_str = "World"
sum_str = a_str + b_str
print("String concatenation:", sum_str)
print("Type:", type(sum_str))
